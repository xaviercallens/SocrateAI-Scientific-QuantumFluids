"""Cohn-Kumar two-point linear-programming lower bound for the Gaussian energy e^{-alpha r^2}
per particle at unit density in R^d (registered: PREREG_round2.md, section H1).

Fourier convention: fhat(y) = int f(x) e^{-2 pi i x.y} dx.

Bound (proof sketch in RESULTS.md): f radial Schwartz, f(x) <= g(x) := e^{-alpha|x|^2} for x != 0,
fhat >= 0  =>  E(P) >= fhat(0) - f(0) for every periodic unit-density configuration P.

Ansatz: fhat(y) = e^{-pi|y|^2/beta} p(|y|^2), p polynomial of degree <= K (K <= 30).  The polynomial is
expanded in the radial Hermite (Laguerre) eigenbasis of the Fourier transform in R^d,
    phi_k(y) = e^{-pi|y|^2} L_k^{(d/2-1)}(2 pi |y|^2),   phihat_k = (-1)^k phi_k,
so that with fhat(y) = sum_k c_k phi_k(y/sqrt(beta)) one has, in closed form,
    f(x) = beta^{d/2} sum_k (-1)^k c_k phi_k(sqrt(beta) x).
No numerical Fourier transform is used anywhere.  The scaled Laguerre functions psi_k(t) = e^{-t/2} L_k^{(a)}(t)
are generated by the three-term recurrence (stable, |psi_k| = O(1) for a >= 0).

LP:  maximise  fhat(0) - f(0)  over c in R^{K+1}
     s.t.  f(r_i) <= g(r_i)  on the registered grid r in (0, 6] (2000 pts) plus a tail grid (6, R_tail],
           fhat(y_j) >= 0 on a grid in [0, Y_max],
           sign constraint on the top coefficient (tail behaviour, see below),
     then cutting planes: violated points on very fine grids are appended and the LP re-solved.
Solver: scipy.optimize.linprog, method 'highs' (cvxpy not installed).

Tail certificates (a posteriori, 40-digit mpmath arithmetic because the exponentials underflow in double):
  monomial coefficients of the polynomial factors of f and fhat; Cauchy bound S_big on all roots; sign at infinity from
  the top coefficient (forced by the LP sign constraint with a margin eps_top); on [grid_end^2, S_big] the envelope
  e^{-decay s} sum_m |coef_m| s^m is maximised on a dense log grid and must be <= 1e-12.
Cutting planes: local maxima of the violations on a fine grid are polished by bounded 1-D maximisation and appended.
"""
import json
import math
import numpy as np
from scipy.optimize import linprog
from scipy.special import binom as gbinom


# ----------------------------------------------------------------------------------------------------------
# Laguerre machinery
# ----------------------------------------------------------------------------------------------------------
def psi_matrix(t, K, a):
    """psi_k(t) = e^{-t/2} L_k^{(a)}(t), k = 0..K, for array t >= 0. Returns shape (len(t), K+1)."""
    t = np.asarray(t, dtype=float)
    out = np.empty((t.size, K + 1))
    e = np.exp(-0.5 * t)
    out[:, 0] = e
    if K >= 1:
        out[:, 1] = (1.0 + a - t) * e
    for k in range(1, K):
        out[:, k + 1] = ((2 * k + 1 + a - t) * out[:, k] - (k + a) * out[:, k - 1]) / (k + 1)
    return out


def laguerre_monomial_coeffs(k, a, scale):
    """Coefficients of L_k^{(a)}(scale*s) as a polynomial in s: sum_m coef[m] s^m."""
    coef = np.zeros(k + 1)
    for m in range(k + 1):
        coef[m] = (-1) ** m * gbinom(k + a, k - m) * scale ** m / math.factorial(m)
    return coef


class GaussLP:
    def __init__(self, d, alpha, beta, K=30):
        self.d, self.alpha, self.beta, self.K = d, float(alpha), float(beta), int(K)
        self.a = d / 2.0 - 1.0
        self.c = None

    # f and fhat as linear maps of c -------------------------------------------------------------------------
    def f_rows(self, r):
        """Matrix F with f(r) = F @ c."""
        r = np.asarray(r, dtype=float)
        P = psi_matrix(2 * math.pi * self.beta * r * r, self.K, self.a)
        signs = (-1.0) ** np.arange(self.K + 1)
        return self.beta ** (self.d / 2.0) * P * signs

    def fhat_rows(self, y):
        y = np.asarray(y, dtype=float)
        return psi_matrix(2 * math.pi * y * y / self.beta, self.K, self.a)

    def g(self, r):
        return np.exp(-self.alpha * np.asarray(r, dtype=float) ** 2)

    def f(self, r):
        return self.f_rows(r) @ self.c

    def fhat(self, y):
        return self.fhat_rows(y) @ self.c

    def objective_vector(self):
        """fhat(0) - f(0) = obj @ c."""
        return (self.fhat_rows([0.0]) - self.f_rows([0.0]))[0]

    # LP ---------------------------------------------------------------------------------------------------
    def _polished_violations(self, x_fine, v_fine, func, n_keep, tol):
        """Local maxima of the violation v on the fine grid, polished by bounded 1-D maximisation of func
        between the neighbouring grid points.  Returns (points, polished violations)."""
        from scipy.optimize import minimize_scalar
        v = v_fine
        loc = np.nonzero((v[1:-1] >= v[:-2]) & (v[1:-1] >= v[2:]) & (v[1:-1] > tol))[0] + 1
        if loc.size == 0:
            return np.empty(0), np.empty(0)
        loc = loc[np.argsort(v[loc])[::-1][:n_keep]]
        pts, vals = [], []
        for i in loc:
            lo, hi = x_fine[i - 1], x_fine[i + 1]
            try:
                r = minimize_scalar(lambda x: -func(np.array([x]))[0], bounds=(lo, hi), method="bounded",
                                    options={"xatol": 1e-13, "maxiter": 200})
                xs, vs = float(r.x), float(-r.fun)
            except Exception:
                xs, vs = float(x_fine[i]), float(v[i])
            if vs < v[i]:
                xs, vs = float(x_fine[i]), float(v[i])
            pts.append(xs)
            vals.append(vs)
        return np.array(pts), np.array(vals)

    def _lp(self, A, b, obj, bounds, tol_lp):
        """HiGHS with a fallback chain (status 15 'Unknown' was observed at tight tolerances)."""
        chain = [("highs", tol_lp), ("highs-ds", tol_lp), ("highs-ipm", tol_lp), ("highs", 1e-9), ("highs-ipm", 1e-9)]
        last = None
        for method, tol in chain:
            res = linprog(-obj, A_ub=A, b_ub=b, bounds=bounds, method=method,
                          options={"primal_feasibility_tolerance": tol, "dual_feasibility_tolerance": tol,
                                   "ipm_optimality_tolerance": 1e-12, "presolve": True})
            last = res
            if res.status == 0:
                res.used = (method, tol)
                return res
        last.used = None
        return last

    def solve(self, n_r=2000, r_max=6.0, r_tail=24.0, n_tail=600, y_max=12.0, n_y=2400,
              rounds=12, n_fine=200000, cut_per_round=200, tol_cut=1e-13, tol_lp=1e-10, eps_top=1e-10,
              verbose=False):
        beta, alpha, K = self.beta, self.alpha, self.K
        r_grid = r_max * np.arange(1, n_r + 1) / n_r                     # registered: (0, 6], 2000 points
        r_tailg = r_max + (r_tail - r_max) * np.arange(1, n_tail + 1) / n_tail
        y_grid = y_max * np.arange(0, n_y + 1) / n_y
        R = np.concatenate([r_grid, r_tailg])
        Y = y_grid.copy()
        obj = self.objective_vector()
        # Top-coefficient sign constraint (tail consistency).  Top monomial of the polynomial factor of f:
        #   a_K = c_K (2 pi beta)^K / K!  (positive multiple of c_K);  of p:  b_K = (-1)^K c_K (2 pi/beta)^K / K!.
        # fhat >= 0 at infinity needs b_K > 0.  If pi beta <= alpha, f must be <= 0 at infinity (it decays slower
        # than g), i.e. a_K < 0.  Both together force c_K = 0 for even K; we then use odd K_eff with c_K < 0.
        # A margin eps_top keeps the top coefficient strictly non-zero so that the sign at infinity is fixed.
        bounds = [(None, None)] * (K + 1)
        if math.pi * beta > alpha:
            bounds[K] = (eps_top, None) if K % 2 == 0 else (None, -eps_top)       # b_K > 0
            self.tail_mode = "f decays faster than g; top coefficient of p forced > 0"
        else:
            if K % 2 == 0:
                bounds[K] = (0.0, 0.0)
                bounds[K - 1] = (None, -eps_top)                            # a_{K-1} < 0 and b_{K-1} > 0
            else:
                bounds[K] = (None, -eps_top)
            self.tail_mode = "f decays slower than g: odd effective degree, f < 0 and p > 0 at infinity forced"
        hist = []
        rng = np.random.default_rng(12345)
        used = None
        for it in range(rounds):
            A_f = self.f_rows(R)
            b_f = self.g(R)
            A_h = -self.fhat_rows(Y)
            b_h = np.zeros(Y.size)
            A = np.vstack([A_f, A_h])
            b = np.concatenate([b_f, b_h])
            res = self._lp(A, b, obj, bounds, tol_lp)
            if res.status != 0:
                return {"status": res.status, "message": res.message, "bound": None}
            used = res.used
            self.c = res.x
            bound = float(obj @ self.c)
            # fine-grid violation search, polished local maxima -> cutting planes
            r_fine = np.sort(np.concatenate([r_tail * (np.arange(1, n_fine + 1) / n_fine),
                                             rng.uniform(1e-6, r_tail, n_fine // 2)]))
            y_fine = np.sort(np.concatenate([y_max * np.arange(0, n_fine + 1) / n_fine,
                                             rng.uniform(0, y_max, n_fine // 2)]))
            vf = self.f(r_fine) - self.g(r_fine)
            vh = -self.fhat(y_fine)
            pf, vpf = self._polished_violations(r_fine, vf, lambda x: self.f(x) - self.g(x), cut_per_round, tol_cut)
            ph, vph = self._polished_violations(y_fine, vh, lambda x: -self.fhat(x), cut_per_round, tol_cut)
            mf = float(max(vf.max(), vpf.max() if vpf.size else -np.inf))
            mh = float(max(vh.max(), vph.max() if vph.size else -np.inf))
            hist.append({"round": it, "bound": bound, "max_f_minus_g": mf, "max_neg_fhat": mh,
                         "n_constraints": int(A.shape[0]), "n_dips_f": int(pf.size), "n_dips_fhat": int(ph.size)})
            if verbose:
                print(f"  round {it}: bound={bound:.12f} viol f-g={mf:.2e} -fhat={mh:.2e} rows={A.shape[0]} "
                      f"dips={pf.size}/{ph.size} lp={used}")
            if max(mf, mh) <= tol_cut:
                break
            # add polished dip locations and their immediate fine-grid neighbours
            if pf.size:
                R = np.concatenate([R, pf, r_fine[np.argsort(vf)[-cut_per_round:]]])
            if ph.size:
                Y = np.concatenate([Y, ph, y_fine[np.argsort(vh)[-cut_per_round:]]])
        cert = self.tail_certificates(r_far=r_tail, y_far=y_max)
        return {"status": 0, "bound": bound, "beta": beta, "alpha": alpha, "d": self.d, "K": K,
                "coeffs": self.c.tolist(), "history": hist, "final_max_f_minus_g": mf, "final_max_neg_fhat": mh,
                "tail_certificates": cert, "lp_iterations": int(res.nit), "lp_method": f"scipy linprog {used}",
                "tail_mode": self.tail_mode, "eps_top": eps_top}

    # Certificates -----------------------------------------------------------------------------------------
    def poly_coeffs(self):
        """Monomial coefficients (in s = r^2 resp. s = |y|^2) of the polynomial factors of f and fhat."""
        K, a, beta, c = self.K, self.a, self.beta, self.c
        af = np.zeros(K + 1)
        bh = np.zeros(K + 1)
        for k in range(K + 1):
            if c[k] == 0.0:
                continue
            af[: k + 1] += c[k] * (-1) ** k * laguerre_monomial_coeffs(k, a, 2 * math.pi * beta)
            bh[: k + 1] += c[k] * laguerre_monomial_coeffs(k, a, 2 * math.pi / beta)
        af *= beta ** (self.d / 2.0)
        return af, bh

    def _mp_poly_coeffs(self):
        """Monomial coefficients of the polynomial factors, in mpmath (40 digits):  f(x) = e^{-pi beta s} P_f(s),
        fhat(y) = e^{-pi s/beta} p(s), s = r^2 resp. |y|^2."""
        import mpmath as mp
        mp.mp.dps = 40
        K, a, beta = self.K, mp.mpf(self.a), mp.mpf(self.beta)
        af = [mp.mpf(0)] * (K + 1)
        bh = [mp.mpf(0)] * (K + 1)
        for k in range(K + 1):
            ck = mp.mpf(float(self.c[k]))
            if ck == 0:
                continue
            for m in range(k + 1):
                lag = (-1) ** m * mp.binomial(k + a, k - m) / mp.factorial(m)
                af[m] += ck * (-1) ** k * lag * (2 * mp.pi * beta) ** m
                bh[m] += ck * lag * (2 * mp.pi / beta) ** m
        af = [x * beta ** (mp.mpf(self.d) / 2) for x in af]
        return af, bh

    @staticmethod
    def _tail_scan(coeffs, decay, s0, extra=None, n=3000):
        """For h(s) = e^{-decay s} sum_m coeffs[m] s^m on [s0, inf): Cauchy root bound S_big, dense log-grid minimum
        of h (and of h - extra(s) if given) on [s0, S_big], and the envelope e^{-decay s} sum |coeffs[m]| s^m max.
        Beyond S_big the sign of h is the sign of the top coefficient (all real roots lie in [-S_big, S_big])."""
        import mpmath as mp
        M = max(m for m in range(len(coeffs)) if coeffs[m] != 0)
        top = coeffs[M]
        S_big = 1 + max([abs(coeffs[m] / top) for m in range(M)] + [mp.mpf(0)])
        S_big = max(S_big, mp.mpf(s0) * 1.0001)
        grid = [mp.mpf(s0) * (S_big / mp.mpf(s0)) ** (mp.mpf(i) / (n - 1)) for i in range(n)]
        hmin, envmax, vmax = mp.inf, mp.mpf(0), -mp.inf
        for s in grid:
            e = mp.exp(-decay * s)
            val = e * mp.polyval(list(reversed(coeffs)), s)
            env = e * mp.polyval(list(reversed([abs(c) for c in coeffs])), s)
            hmin = min(hmin, val)
            envmax = max(envmax, env)
            if extra is not None:
                vmax = max(vmax, val - extra(s))
        return {"top_degree": int(M), "top_coeff": float(top), "S_big": float(S_big), "grid_min": float(hmin),
                "envelope_max": float(envmax), "grid_max_minus_extra": (float(vmax) if extra is not None else None)}

    def tail_certificates(self, r_far, y_far):
        """Tail analysis beyond the constraint grids, in 40-digit arithmetic (the exponentials underflow in double).
        fhat: ok iff top coefficient of p > 0 (sign at infinity) and the envelope on [y_far^2, S_big] is <= 1e-12,
              so any negative excursion there is below 1e-12 in absolute value (grid_min is the dense-grid minimum).
        f:    ok iff (top coefficient of P_f < 0) or (pi beta > alpha, so f/g -> 0 at infinity), and the envelope
              of |f| on [r_far^2, S_big] is <= 1e-12 (then f - g <= 1e-12 there; grid_max_minus_extra is the dense-grid
              maximum of f - g)."""
        import mpmath as mp
        af, bh = self._mp_poly_coeffs()
        out = {}
        th = self._tail_scan(bh, mp.pi / mp.mpf(self.beta), y_far ** 2)
        th.update({"y_far": y_far, "sign_at_infinity_ok": th["top_coeff"] > 0,
                   "ok": bool(th["top_coeff"] > 0 and th["envelope_max"] <= 1e-12)})
        out["fhat_tail"] = th
        alpha = mp.mpf(self.alpha)
        tf = self._tail_scan(af, mp.pi * mp.mpf(self.beta), r_far ** 2, extra=lambda s: mp.exp(-alpha * s))
        sign_ok = (tf["top_coeff"] < 0) or (math.pi * self.beta > self.alpha)
        tf.update({"r_far": r_far, "mode": "negative_tail" if tf["top_coeff"] < 0 else
                   ("positive_tail_faster_than_g" if math.pi * self.beta > self.alpha else "positive_tail_slower_than_g"),
                   "sign_at_infinity_ok": bool(sign_ok),
                   "ok": bool(sign_ok and tf["envelope_max"] <= 1e-12)})
        out["f_tail"] = tf
        return out

    def verify_random(self, n=100000, r_max=24.0, seed=2026):
        """Registered verification: f <= g on n random radii; also fhat >= 0 on n random |y|."""
        rng = np.random.default_rng(seed)
        r = np.concatenate([rng.uniform(0, r_max, n - n // 5), 10 ** rng.uniform(-6, math.log10(r_max), n // 5)])
        r = r[r > 0]
        vf = self.f(r) - self.g(r)
        y = rng.uniform(0, r_max, n)
        vh = -self.fhat(y)
        return {"n_random": int(r.size), "max_f_minus_g": float(vf.max()), "argmax_r": float(r[np.argmax(vf)]),
                "max_neg_fhat": float(vh.max()), "argmax_y": float(y[np.argmax(vh)])}


def best_over_beta(d, alpha, betas, K=30, verbose=False, **kw):
    results = []
    best = None
    for beta in betas:
        lp = GaussLP(d, alpha, beta, K)
        res = lp.solve(verbose=verbose, **kw)
        if res["bound"] is None:
            results.append({"beta": beta, "status": res["status"], "message": res["message"]})
            if verbose:
                print(f" beta={beta:.5f}: LP failed ({res['message']})")
            continue
        ok = res["tail_certificates"]["fhat_tail"]["ok"] and res["tail_certificates"]["f_tail"]["ok"]
        viol_ok = max(res["final_max_f_minus_g"], res["final_max_neg_fhat"]) <= 1e-10
        results.append({"beta": beta, "bound": res["bound"], "certificates_ok": ok, "violations_ok": viol_ok,
                        "max_f_minus_g": res["final_max_f_minus_g"], "max_neg_fhat": res["final_max_neg_fhat"]})
        if verbose:
            print(f" beta={beta:.5f}: bound={res['bound']:.12f} cert_ok={ok} viol_ok={viol_ok}")
        if ok and viol_ok and (best is None or res["bound"] > best[0]["bound"]):
            best = (res, lp)
    return best, results


