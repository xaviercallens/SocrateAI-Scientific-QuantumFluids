# Reference energies (direct lattice sums, tails < 1e-15)
# ----------------------------------------------------------------------------------------------------------
def theta_sum(B, alpha, R=None):
    """sum_{v in L \\ 0} e^{-alpha |v|^2}, L spanned by rows of B. Cut-off R chosen so the tail < 1e-15:
    the number of lattice points in a shell is bounded crudely; we take R with alpha R^2 >= 60 and R >= 7."""
    B = np.asarray(B, dtype=float)
    d = B.shape[0]
    if R is None:
        R = max(7.0, math.sqrt(60.0 / alpha))
    n = int(R / np.min(np.linalg.norm(B, axis=1)) * 2) + 2
    rng = np.arange(-n, n + 1)
    grids = np.meshgrid(*([rng] * d), indexing="ij")
    I = np.stack([g.ravel() for g in grids], axis=1)
    V = I @ B
    r2 = (V ** 2).sum(1)
    r2 = r2[r2 > 1e-12]
    r2 = r2[r2 <= R * R]
    # tail estimate: points with |v| in (R, R+1] times e^{-alpha R^2}: crude bound, must be < 1e-15
    tail = (len(r2) + 1) * 10 * math.exp(-alpha * R * R)
    return float(np.exp(-alpha * r2).sum()), tail


def bct(t):
    """Body-centred tetragonal at unit density, c/a = t (t = 1 BCC, t = sqrt 2 FCC); as AB/bain_selfdual.py."""
    a = (2 / t) ** (1 / 3)
    c = t * a
    return np.array([[a, 0, 0], [0, a, 0], [a / 2, a / 2, c / 2]])


def lattice(name):
    if name == "Z":
        return np.array([[1.0]])
    if name == "A2":
        a = math.sqrt(2 / math.sqrt(3))
        return a * np.array([[1.0, 0.0], [0.5, math.sqrt(3) / 2]])
    if name == "BCC":
        return bct(1.0)
    if name == "FCC":
        return bct(math.sqrt(2))
    raise ValueError(name)


def E_Z_series(alpha, nmax=60):
    n = np.arange(1, nmax + 1)
    return 2 * float(np.exp(-alpha * n * n).sum())
